import ast
import json
import os

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.isotonic import IsotonicRegression
from sklearn.metrics import average_precision_score, f1_score, roc_auc_score

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "ptbxl_baseline")
CLASSES = ["NORM", "MI", "STTC", "CD", "HYP"]
QUALITY_FIELDS = [
    "baseline_drift",
    "static_noise",
    "burst_noise",
    "electrodes_problems",
]


def log(msg: str) -> None:
    print(msg, flush=True)


def present(series: pd.Series) -> pd.Series:
    text = series.fillna("").astype(str).str.strip()
    return text.ne("") & text.str.lower().ne("nan")


def diagnostic_matrix(database: pd.DataFrame, statements: pd.DataFrame) -> pd.DataFrame:
    diagnostic = statements[statements["diagnostic"] == 1]
    class_of = diagnostic["diagnostic_class"].dropna().to_dict()
    rows = []
    for codes in database["scp_codes"]:
        found = {name: 0 for name in CLASSES}
        for code, likelihood in ast.literal_eval(codes).items():
            if likelihood <= 0 or code not in class_of:
                continue
            superclass = class_of[code]
            if superclass in found:
                found[superclass] = 1
        rows.append(found)
    return pd.DataFrame(rows, index=database.index)


def expected_calibration_error(y_true: np.ndarray, y_prob: np.ndarray, bins: int = 10) -> float:
    edges = np.linspace(0.0, 1.0, bins + 1)
    error = 0.0
    for start, stop in zip(edges[:-1], edges[1:]):
        if stop == 1.0:
            mask = (y_prob >= start) & (y_prob <= stop)
        else:
            mask = (y_prob >= start) & (y_prob < stop)
        if not np.any(mask):
            continue
        error += mask.mean() * abs(y_true[mask].mean() - y_prob[mask].mean())
    return float(error)


def binary_entropy(prob: np.ndarray) -> np.ndarray:
    p = np.clip(prob, 1e-6, 1 - 1e-6)
    return -(p * np.log(p) + (1 - p) * np.log(1 - p)) / np.log(2)


def sample_weights(y: np.ndarray) -> np.ndarray:
    positive = max(y.mean(), 1e-6)
    negative = max(1 - positive, 1e-6)
    return np.where(y == 1, 0.5 / positive, 0.5 / negative)


def fit_label(x_train: np.ndarray, y_train: np.ndarray) -> HistGradientBoostingClassifier:
    model = HistGradientBoostingClassifier(
        max_iter=120,
        learning_rate=0.08,
        max_leaf_nodes=31,
        early_stopping=True,
        validation_fraction=0.1,
        n_iter_no_change=10,
        random_state=0,
    )
    model.fit(x_train, y_train, sample_weight=sample_weights(y_train))
    return model


def hamming_loss(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean(y_true != y_pred))


def selective_table(y_true: np.ndarray, y_prob: np.ndarray, confidence: np.ndarray) -> dict:
    order = np.argsort(-confidence)
    rows = {}
    for coverage in (1.0, 0.8, 0.5):
        count = max(1, int(round(coverage * len(order))))
        chosen = order[:count]
        pred = (y_prob[chosen] >= 0.5).astype(int)
        rows[f"{coverage:.1f}"] = {
            "n": int(count),
            "hamming_loss": hamming_loss(y_true[chosen], pred),
            "macro_f1": float(f1_score(y_true[chosen], pred, average="macro", zero_division=0)),
        }
    return rows


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    database = pd.read_csv(os.path.join(ROOT, "ptb-xl", "ptbxl_database.csv"))
    statements = pd.read_csv(os.path.join(ROOT, "ptb-xl", "scp_statements.csv"), index_col=0)
    features = pd.read_csv(os.path.join(ROOT, "ptb-xl-plus", "features", "12sl_features.csv"))

    labels = diagnostic_matrix(database, statements)
    frame = pd.concat([database, labels], axis=1)
    frame = frame[labels.sum(axis=1) > 0].copy()
    frame = frame.merge(features, on="ecg_id", how="inner", validate="one_to_one")

    for field in QUALITY_FIELDS + ["extra_beats", "pacemaker"]:
        frame[f"has_{field}"] = present(frame[field]).astype(int)
    frame["signal_quality_issue"] = (frame[[f"has_{field}" for field in QUALITY_FIELDS]].sum(axis=1) > 0).astype(int)
    frame["validated_by_human"] = frame["validated_by_human"].astype(bool)
    frame["initial_autogenerated_report"] = frame["initial_autogenerated_report"].astype(bool)
    frame["second_opinion"] = frame["second_opinion"].astype(bool)

    feature_columns = [column for column in features.columns if column != "ecg_id"]
    x = frame[feature_columns].apply(pd.to_numeric, errors="coerce").to_numpy(dtype=np.float32)
    y = frame[CLASSES].to_numpy(dtype=int)
    train = frame["strat_fold"].between(1, 8).to_numpy()
    calibrate = frame["strat_fold"].eq(9).to_numpy()
    test = frame["strat_fold"].eq(10).to_numpy()

    patients = {
        "train": set(frame.loc[train, "patient_id"]),
        "calibrate": set(frame.loc[calibrate, "patient_id"]),
        "test": set(frame.loc[test, "patient_id"]),
    }
    if patients["train"] & patients["test"] or patients["calibrate"] & patients["test"]:
        raise RuntimeError("patient overlap between development and test folds")

    raw = np.zeros_like(y, dtype=np.float64)
    calibrated = np.zeros_like(y, dtype=np.float64)
    for index, name in enumerate(CLASSES):
        log(f"fit {name}")
        model = fit_label(x[train], y[train, index])
        raw[:, index] = model.predict_proba(x)[:, 1]
        calibrator = IsotonicRegression(out_of_bounds="clip")
        calibrator.fit(raw[calibrate, index], y[calibrate, index])
        calibrated[:, index] = calibrator.predict(raw[:, index])

    confidence = 1 - binary_entropy(calibrated).mean(axis=1)
    prediction = (calibrated >= 0.5).astype(int)

    def score(split: np.ndarray, prob: np.ndarray) -> dict:
        return {
            "n": int(split.sum()),
            "macro_auroc": float(roc_auc_score(y[split], prob[split], average="macro")),
            "macro_auprc": float(average_precision_score(y[split], prob[split], average="macro")),
            "macro_f1": float(f1_score(y[split], (prob[split] >= 0.5).astype(int), average="macro", zero_division=0)),
            "macro_ece": float(np.mean([
                expected_calibration_error(y[split, i], prob[split, i]) for i in range(len(CLASSES))
            ])),
            "per_class": {
                name: {
                    "auroc": float(roc_auc_score(y[split, i], prob[split, i])),
                    "auprc": float(average_precision_score(y[split, i], prob[split, i])),
                    "f1": float(f1_score(y[split, i], (prob[split, i] >= 0.5).astype(int), zero_division=0)),
                    "ece": expected_calibration_error(y[split, i], prob[split, i]),
                    "prevalence": float(y[split, i].mean()),
                }
                for i, name in enumerate(CLASSES)
            },
        }

    test_metrics = score(test, calibrated)
    test_metrics["selective_risk"] = selective_table(y[test], calibrated[test], confidence[test])
    test_metrics["uncalibrated_macro_ece"] = float(np.mean([
        expected_calibration_error(y[test, i], raw[test, i]) for i in range(len(CLASSES))
    ]))

    record = frame[
        [
            "ecg_id",
            "patient_id",
            "strat_fold",
            "age",
            "sex",
            "signal_quality_issue",
            "has_baseline_drift",
            "has_static_noise",
            "has_burst_noise",
            "has_electrodes_problems",
            "has_extra_beats",
            "has_pacemaker",
            "validated_by_human",
            "initial_autogenerated_report",
            "second_opinion",
        ]
    ].copy()
    record["split"] = np.where(train, "train", np.where(calibrate, "calibrate", "test"))
    for index, name in enumerate(CLASSES):
        record[f"y_{name}"] = y[:, index]
        record[f"p_{name}"] = calibrated[:, index]
    record["confidence"] = confidence
    record["hamming_error"] = np.mean(y != prediction, axis=1)
    record.to_csv(os.path.join(OUT, "case_record.csv"), index=False)

    summary = {
        "task": "PTB-XL diagnostic superclasses, multi-label",
        "features": "PTB-XL+ 12SL measurements",
        "model": "class-weighted histogram gradient boosting, isotonic calibration on fold 9",
        "split": {"train_folds": "1-8", "calibration_fold": 9, "test_fold": 10},
        "n_records": int(len(frame)),
        "n_patients": int(frame["patient_id"].nunique()),
        "n_features": len(feature_columns),
        "label_counts": {name: int(frame[name].sum()) for name in CLASSES},
        "signal_quality_issue_rate": float(frame["signal_quality_issue"].mean()),
        "human_validated_rate": float(frame["validated_by_human"].mean()),
        "initially_autogenerated_rate": float(frame["initial_autogenerated_report"].mean()),
        "second_opinion_rate": float(frame["second_opinion"].mean()),
        "test": test_metrics,
    }
    with open(os.path.join(OUT, "metrics.json"), "w", encoding="utf-8") as handle:
        json.dump(summary, handle, indent=2)
    log(json.dumps({k: summary[k] for k in ("n_records", "n_patients", "test")}, indent=2))


if __name__ == "__main__":
    main()
